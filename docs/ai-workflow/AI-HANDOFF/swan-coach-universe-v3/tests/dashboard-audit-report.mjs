/** Generate the complete route denominator from the static audit, without claiming live QA. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const packet = fileURLToPath(new URL('../', import.meta.url));
const input = JSON.parse(fs.readFileSync(path.join(packet, 'evidence/astra-dashboard-inventory.json'), 'utf8'));
const categories = [
  [/ai-consent/, 'D24 AI consent', 'Existing explicit consent controls; revocation invalidates inference and memory'],
  [/coach-assistant|\/plaud/, 'D01 Coach/intake', 'Context, draft, review, receipt; maintain protocol separation'],
  [/workout-planner|build-plan|workout-forge|workouts\/:/, 'D02 Planner', 'Canonical plan/exercise draft; review edits and invalidate preview'],
  [/log-workout|log-my-workout|\/workouts$/, 'D03 Logger', 'One canonical workout save and verified diary/progress result'],
  [/bootcamp|sprint-planner/, 'D04 Group training', 'Editable class/sprint draft; resolve event receiver before save'],
  [/client-management|client-details|\/clients$/, 'D05 Clients/team', 'Authorized target, profile and shared task; no selection-based authority'],
  [/onboarding/, 'D06 Onboarding', 'Read readiness; draft permitted fields; existing consent gates'],
  [/waivers/, 'D07 Waivers', 'Read clearance metadata; open human review; no invented legal acceptance'],
  [/master-schedule|\/schedule$|admin-sessions/, 'D08 Schedule/location', 'Slots/location preflight; reviewed booking with credit/conflict recheck'],
  [/trainer-management|trainer-permissions|client-trainer-assignments/, 'D09 Staff/assignments', 'Current assignment/permission reads; deliberate existing admin workflow'],
  [/session-allocation|packages|specials|orders|revenue|payouts|earnings|pricing-sheet/, 'D10 Money/credits', 'Authorized explanation and existing UI; no new autonomous financial writes'],
  [/body-map/, 'D11 Pain', 'Current symptom evidence; reviewed report; no diagnosis/clearance inference'],
  [/nutrition|meal-planner/, 'D12 Nutrition', 'Keep food log and target-plan authority distinct; draft and review'],
  [/equipment/, 'D13 Equipment', 'Location gear context; verified owned profile; reviewed item changes'],
  [/assessments|video-call/, 'D14 Assessment', 'Consent and assessment evidence; no diagnosis from media'],
  [/gamification|rewards|challenges|olympics|my-home|badge-creator/, 'D15 Progress/rewards', 'Read earned facts; explain next step; no arbitrary award or paid generation'],
  [/content|gallery|photos|videos|\/live$|creators|creative|reels/, 'D16 Media/content', 'Authorized discovery and draft; distinct upload/publish/audience approval'],
  [/account-access|user-management|feature-access|launch-control|security/, 'D17 Access/system', 'Explain/navigate; preserve deliberate admin-only security authority'],
  [/messages|support|automation|sms-logs|marketing|notifications/, 'D18 Communication', 'Draft/inspect only; separate explicit send, retention and audience policy'],
  [/client-progress|\/progress/, 'D19 Progress analytics', 'Deterministic source-linked metrics; missing data stays unavailable'],
  [/community|groups|friends|\/about$|\/activity$|\/profile$/, 'D20 Community/profile', 'Own/visible content only; draft profile/community changes without auto-publish'],
  [/notes/, 'D21 Notes', 'Scoped notes are data, not instructions; no staff-note leakage'],
  [/design-playground|style-guide|workout-design-lab|immigration/, 'D22 Specialized/admin', 'Context/navigation only; no public operator tools or unrelated legal guidance'],
  [/overview|user-dashboard$/, 'D23 Dashboard home', 'Role-aware useful next action from real training evidence'],
];
let missing = [];
const lines = [
  '# SCU-DASHBOARD-AUDIT — every top-level route/tab',
  '',
  'Owner: Astra. Version: 3.2, 2026-09-06 UTC. Status: source inventory and integration classification.',
  'Supersedes: any assumption that the three role dashboards include the general User dashboard.',
  '',
  'Generated by tests/dashboard-audit-report.mjs from the AST inventory. Every route gets a row.',
  'Counts include configured secondary routes, wrappers and redirects; they are not counts of visible sidebar buttons.',
  'Import/API/Coach JSX candidates are in evidence/astra-dashboard-inventory.json, with line references.',
  'Candidates need a real caller/handler walk before mutation; missing candidates do not prove no API exists.',
  'Conditional entitlement visibility and authenticated browser journeys remain OPEN.',
  'See 19-one-coach-domain-contracts.md for each D-code contract and negative tests.',
  '',
  'Mount proof: UniversalDashboardLayout.shell.tsx:133 -> shellPieces.tsx:94-108 -> Component.',
  'User mount is separate: main-routes.tsx -> UserDashboard.V3 -> UserDashboardTabsV3 TabPanel.',
  'Admin navigation uses config/dashboard-tabs.ts WORKSPACE_CONFIG; trainer/client have role sidebars.',
  'Legacy routes can still be active redirects or active legacy pages. Do not delete by name.',
  '',
];
for (const role of ['admin','trainer','client','user']) {
  lines.push('## ' + role + ' — ' + input.counts[role] + ' entries', '',
    '| Route | Mounted component | Classification | One Coach integration |',
    '|---|---|---|---|');
  for (const route of input.routes.filter((r) => r.role === role)) {
    const category = categories.find(([pattern]) => pattern.test(route.path));
    if (!category) missing.push(route.path);
    const cell = category ? category[1] + ': ' + category[2] : 'UNRESOLVED: explicit disposition required';
    lines.push('| ' + route.path + ' | ' + route.component + ' | ' + route.classification + ' | ' + cell + ' |');
  }
  lines.push('');
}
lines.push('## Nested surfaces and known audit limits', '',
  '- Clients & Team contains its own training, progress, nutrition, biometrics and team subviews; expand them in the D05 receipt.',
  '- Schedule location is a field/resource workflow; Session Allocation is a separate credits workflow, not a location alias.',
  '- Content Studio, galleries, nutrition, planner, equipment and settings have internal panels; their candidate IDs are retained in JSON.',
  '- Redirect wrappers are deliberately not traversed as whole modules: that would falsely attribute unrelated page APIs to them.',
  '- The import traversal is bounded to four hops and 100 files per route. Truncated routes are named in the JSON/run output.',
  '- This inventory proves route coverage, not 127 completed browser audits or 127 connected Coach tools.',
  '- Every new adapter still needs owner/model/endpoint evidence and the domain negative tests before it can activate.',
  '');
fs.writeFileSync(path.join(packet, '18-dashboard-tab-audit.md'), lines.join('\n'));
process.stdout.write(JSON.stringify({ routes: input.routes.length, counts: input.counts, unresolved: missing, lines: lines.length }, null, 2));
