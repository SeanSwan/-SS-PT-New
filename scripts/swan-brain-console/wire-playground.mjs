/**
 * wire-playground — generate the Design Studio entries for the 20-variant fleet.
 * @module scripts/swan-brain-console/wire-playground
 *
 * WHY GENERATED
 * Twenty hand-written registry entries would drift from the fleet the moment a
 * variant is renamed. The generator reads the canonical `registry.ts` prose and
 * the canonical id list straight from the repo and writes ONE file,
 * `DesignPlayground/threeWorldEntries.ts`, which `playgroundRegistry.ts` spreads.
 * Re-run this after adding or renaming a variant.
 *
 * The generated entries are lazily imported, so none of the twenty scenes (or
 * three.js itself) enters the initial bundle. Each is labelled with its own
 * divergence tuple so the Design Studio can show a real caption per artboard.
 *
 * Run: node scripts/swan-brain-console/wire-playground.mjs
 */
import { writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..', '..');
const WORLDS = join(REPO, 'frontend/src/pages/HomePage/three-worlds');
const OUT = join(REPO, 'frontend/src/pages/DesignPlayground/threeWorldEntries.ts');

/** Prose lives in registry.ts as `vNN: '...'` pairs; read it as text. */
function readRecord(src, name) {
  const start = src.indexOf(`const ${name}`);
  if (start === -1) return {};
  const open = src.indexOf('{', start);
  const close = src.indexOf('\n};', open);
  const body = src.slice(open, close === -1 ? undefined : close);
  const out = {};
  const re = /(v\d{2}):\s*'((?:[^'\\]|\\.)*)'/g;
  let m;
  while ((m = re.exec(body)) !== null) out[m[1]] = m[2].replace(/\\'/g, "'");
  return out;
}

const skeletonMod = await import(pathToFileURL(join(WORLDS, 'skeletons.ts')).href);
const registrySrc = readFileSync(join(WORLDS, 'registry.ts'), 'utf8');
const titles = readRecord(registrySrc, 'TITLES');
const tradeoffs = readRecord(registrySrc, 'TRADEOFFS');

const rows = skeletonMod.SKELETONS.map((s) => ({
  id: s.id,
  title: titles[s.id] ?? s.id,
  mechanic: s.hero_mechanics,
  nav: s.nav_model,
  grid: s.grid,
  chapters: s.chapters,
  tradeoff: tradeoffs[s.id] ?? '',
  wildcard: s.wildcard ?? null,
  antiSpecs: s.anti_specs,
}));

/** Render one registry entry. Kept readable on purpose: this file is reviewed. */
function entry(r) {
  const caption = [
    `${r.nav} nav`,
    `${r.mechanic} hero`,
    `${r.grid} grid`,
    `${r.chapters} chapters`,
    r.wildcard ? `WILDCARD: ${r.wildcard}` : null,
  ].filter(Boolean).join(' · ');
  return `  {
    id: 'three-${r.id}',
    title: '${r.id.toUpperCase()} ${r.title.replace(/'/g, "\\'")}',
    lazyImport: () => import('../HomePage/three-worlds/${r.id}/${r.id}'),
    status: 'parked',
    sourceRoute: '/',
    mobbinRefs: [],
    notes: '${caption.replace(/'/g, "\\'")} — ${r.tradeoff.replace(/'/g, "\\'")}',
  },`;
}

const header = `/**
 * threeWorldEntries — Design Studio entries for the 20-variant Three.js fleet.
 * @module pages/DesignPlayground/threeWorldEntries
 *
 * GENERATED by scripts/swan-brain-console/wire-playground.mjs.
 * Do not hand-edit: re-run the generator after changing the fleet registry.
 *
 * Every entry is parked and lazily imported. \`notes\` carries the variant's
 * structural fingerprint plus the cost it accepts, so the Design Studio can
 * caption each artboard honestly instead of presenting twenty anonymous previews.
 *
 * Generated from: ${rows.length} variants.
 */
import type { PlaygroundEntry } from './playgroundTypes';

export const threeWorldEntries: PlaygroundEntry[] = [
`;

if (!existsSync(dirname(OUT))) mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, header + rows.map(entry).join('\n') + '\n];\n', 'utf8');
console.log(`[wire] wrote ${rows.length} entries to ${OUT.replace(REPO + '\\', '')}`);
