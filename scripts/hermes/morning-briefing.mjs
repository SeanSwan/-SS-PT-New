#!/usr/bin/env node
/**
 * morning-briefing.mjs — registered T1 `morning-briefing` (Delivery Quartet Q-1,
 * 7★ gap review): compose ONE morning markdown from everything Sean would
 * otherwise have to go hunting for — last health-sweep, digest attention lines,
 * open approval queue, switch posture, and the repo/agents pulse (pending
 * hermes-inbox memos, last continuity closeout, open review-queue REQs).
 *
 * Labeled DRAFT (T1) per the registry row. Writes runs/digests/briefing-<date>.md
 * and returns { path, attention } — `attention` powers the quiet-on-green
 * delivery rule (UX-11: send only when something needs eyes, weekly full send),
 * which the DELIVERY layer (Hermes cron / slice-5 runner) enforces; this command
 * always renders. Gate: SWITCH_MASTER + SWITCH_MORNING_BRIEFING, fail closed.
 * Repo reads are best-effort — an unreadable source degrades to an honest
 * "unavailable" line, never a crash.
 */
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { listEntries } from './queueModel.mjs';
import {
  checkSwitches, readSwitches, readReceipts, resolveSwitchesFile, resolveVaultRoot,
  vaultPaths, writeReceipt,
} from './hermesRunsLib.mjs';

const HERE = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
const DEFAULT_REPO_ROOT = path.resolve(HERE, '..', '..');
const tryRead = (file) => { try { return fs.readFileSync(file, 'utf8'); } catch { return null; } };

function repoPulse(repoRoot) {
  const pulse = { inbox: [], continuity: null, openReqs: null };
  try {
    const pending = path.join(repoRoot, '.ai-workflow', 'hermes-inbox', 'pending');
    if (fs.existsSync(pending)) pulse.inbox = fs.readdirSync(pending).filter((n) => n.endsWith('.md'));
  } catch { pulse.inbox = null; }
  const rolling = tryRead(path.join(repoRoot, '.ai-workflow', 'continuity', 'rolling-last-done.md'));
  if (rolling) {
    const topics = [...rolling.matchAll(/\*\*Topic:\*\* (.+)/g)];
    pulse.continuity = topics.length ? topics[topics.length - 1][1].trim() : null;
  }
  const queue = tryRead(path.join(repoRoot, '.ai-workflow', 'coordination', 'review-queue.md'));
  if (queue) pulse.openReqs = queue.split('\n').filter((l) => l.startsWith('Status: OPEN')).length;
  return pulse;
}

export function renderBriefing(vaultRoot, switchesFile, isoDate, { repoRoot = DEFAULT_REPO_ROOT, now } = {}) {
  const when = now || new Date().toISOString();
  checkSwitches(vaultRoot, switchesFile, ['SWITCH_MASTER', 'SWITCH_MORNING_BRIEFING'], {
    who: 'harness/morning-briefing', what: 'morning-briefing (T1)', target: `briefing ${isoDate}`, when,
  });
  let attention = 0;
  const lines = [`# Operator briefing — ${isoDate}`, '', '> DRAFT (T1). Generated by `morning-briefing`; quiet-on-green delivery decides whether this reaches Telegram.', ''];

  // Health: the day's last health-sweep receipt, verbatim.
  const sweeps = readReceipts(vaultRoot, isoDate).filter((r) => r.what === 'health-sweep (T0)');
  const sweep = sweeps[sweeps.length - 1];
  lines.push('## Health');
  if (!sweep) { lines.push('- no health-sweep has run today'); attention += 1; }
  else {
    lines.push(`- ${sweep.outcome}`);
    if (!String(sweep.outcome).startsWith('ok')) attention += 1;
  }

  // Digest attention/integrity lines (the digest stays the detailed artifact).
  const digest = tryRead(vaultPaths(vaultRoot, isoDate).digestFile);
  lines.push('', '## Digest attention');
  if (!digest) lines.push('- no digest rendered for this date yet');
  else {
    const hot = digest.split('\n').filter((l) => /⚠|FLOOD|TRUNCAT|chain break|armed>|REGRESSION/i.test(l)).slice(0, 8);
    if (hot.length) { lines.push(...hot.map((l) => `- ${l.trim()}`)); attention += hot.length; }
    else lines.push('- clean');
  }

  // Open approvals — the queue Sean actually owes decisions on.
  lines.push('', '## Approval queue');
  try {
    const open = listEntries(vaultRoot, switchesFile, { filter: 'open', at: when });
    if (!open.length) lines.push('- empty');
    else {
      attention += open.length;
      for (const e of open.slice(0, 5)) lines.push(`- ${e.id} · ${e.action} → ${e.target} (expires ${e.expiresAt || 'unknown'})`);
      if (open.length > 5) lines.push(`- …and ${open.length - 5} more`);
    }
  } catch (err) { lines.push(`- queue unreadable: ${String(err.message).slice(0, 80)}`); attention += 1; }

  // Switch posture — anything off is worth a line.
  lines.push('', '## Switches');
  const sw = readSwitches(switchesFile);
  if (!sw.ok) { lines.push(`- switches unreadable (${sw.reason}) — everything fails closed`); attention += 1; }
  else {
    const off = Object.entries(sw.state).filter(([, v]) => v !== true).map(([k]) => k);
    lines.push(off.length ? `- OFF: ${off.join(', ')}` : `- all ${Object.keys(sw.state).length} on`);
  }

  // Repo/agents pulse (7★ INT-3: the briefing must see the whole stack).
  const pulse = repoPulse(repoRoot);
  lines.push('', '## Repo / agents');
  lines.push(pulse.inbox === null ? '- hermes-inbox unreadable'
    : pulse.inbox.length ? `- ${pulse.inbox.length} pending hermes-inbox memo(s): ${pulse.inbox.slice(0, 3).join(', ')}${pulse.inbox.length > 3 ? ', …' : ''}`
      : '- hermes-inbox empty');
  lines.push(pulse.continuity ? `- last continuity closeout: ${pulse.continuity}` : '- no continuity closeout found');
  lines.push(pulse.openReqs === null ? '- review-queue unreadable' : `- ${pulse.openReqs} open review request(s) between the agents`);

  lines.push('', `_attention items: ${attention} — ${attention === 0 ? 'quiet-on-green: no send needed' : 'worth a look'}_`, '');
  const outPath = path.join(vaultRoot, 'runs', 'digests', `briefing-${isoDate}.md`);
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, lines.join('\n'));
  writeReceipt(vaultRoot, {
    who: 'harness/morning-briefing', what: 'morning-briefing (T1)', target: `briefing ${isoDate}`, when,
    'approved-by': 'n/a', outcome: `ok — DRAFT briefing rendered (attention: ${attention})`, evidence: outPath,
  });
  return { path: outPath, attention };
}

const isMain = process.argv[1] && import.meta.url.endsWith(process.argv[1].replaceAll('\\', '/').split('/').pop());
if (isMain) {
  const { values } = parseArgs({ options: { date: { type: 'string' } } });
  const isoDate = values.date || new Date().toISOString().slice(0, 10);
  const out = renderBriefing(resolveVaultRoot(), resolveSwitchesFile(), isoDate, {});
  console.log(`${out.path} (attention: ${out.attention})`);
}
