export interface WorkoutLoggerPDFData {
  clientName: string;
  trainerName?: string;
  date: string;
  exercises: PDFExerciseEntry[];
  sessionNotes?: string;
  overallIntensity?: number;
}

export function exportWorkoutLoggerPDF(data: WorkoutLoggerPDFData): void {
  const doc = createPDF();
  let y = addHeader(doc, 'Workout Session Log', `${data.clientName} · ${format(new Date(data.date), 'MMMM d, yyyy')}`);

  // Session info
  y = addSectionTitle(doc, y, 'Session Details');
  y = addKeyValue(doc, y, 'Client', data.clientName);
  if (data.trainerName) y = addKeyValue(doc, y, 'Trainer', data.trainerName);
  y = addKeyValue(doc, y, 'Date', format(new Date(data.date), 'EEEE, MMMM d, yyyy'));
  if (data.overallIntensity) y = addKeyValue(doc, y, 'Intensity', `${data.overallIntensity}/10`);
  y += 3;

  // Summary stats
  const totalSets = data.exercises.reduce((s, ex) => s + ex.sets.length, 0);
  const totalReps = data.exercises.reduce((s, ex) => s + ex.sets.reduce((r, set) => r + set.reps, 0), 0);
  const totalVolume = data.exercises.reduce((s, ex) => s + ex.sets.reduce((v, set) => v + set.weight * set.reps, 0), 0);

  y = addSectionTitle(doc, y, 'Session Summary');
  const summaryStartX = 16;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(...BRAND.textDark);

  const stats = [
    ['Exercises', String(data.exercises.length)],
    ['Total Sets', String(totalSets)],
    ['Total Reps', String(totalReps)],
    ['Total Volume', `${totalVolume.toLocaleString()} lbs`],
  ];
  stats.forEach(([label, val], i) => {
    const x = summaryStartX + i * 42;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.setTextColor(...BRAND.wingPurple);
    doc.text(val, x, y + 2);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(...BRAND.textMuted);
    doc.text(label, x, y + 7);
  });
  y += 14;

  // Exercise tables
  data.exercises.forEach((ex, idx) => {
    y = checkPageBreak(doc, y, 30);
    y = addSectionTitle(doc, y, `${idx + 1}. ${ex.exerciseName}`);

    const meta: string[] = [];
    if (ex.formRating) meta.push(`Form: ${ex.formRating}/5`);
    if (ex.painLevel > 0) meta.push(`Pain: ${ex.painLevel}/10`);
    if (ex.performanceNotes) meta.push(ex.performanceNotes);
    if (meta.length) {
      doc.setFont('helvetica', 'italic');
      doc.setFontSize(7);
      doc.setTextColor(...BRAND.textMuted);
      doc.text(meta.join(' · '), 16, y);
      y += 4;
    }

    addAutoTable(doc, {
      startY: y,
      head: [['Set', 'Weight (lbs)', 'Reps', 'RPE', 'Form', 'Tempo', 'Rest (s)', 'Notes']],
      body: ex.sets.map(s => [
        s.setNumber,
        s.weight || '-',
        s.reps,
        s.rpe ? `${s.rpe}/10` : '-',
        s.formQuality ? `${s.formQuality}/5` : '-',
        s.tempo || '-',
        s.restTime || '-',
        s.notes || '',
      ]),
      theme: 'grid',
      headStyles: {
        fillColor: BRAND.midnightSapphire,
        textColor: BRAND.white,
        fontSize: 7,
        fontStyle: 'bold',
        halign: 'center',
      },
      bodyStyles: { fontSize: 7, textColor: BRAND.textDark, halign: 'center' },
      alternateRowStyles: { fillColor: BRAND.lightGray },
      styles: { cellPadding: 2, lineColor: BRAND.borderGray, lineWidth: 0.2 },
      margin: { left: 16, right: 16 },
    });

    y = getLastAutoTableY(doc, y) + 6;
  });

  // Session notes
  if (data.sessionNotes) {
    y = checkPageBreak(doc, y, 20);
    y = addSectionTitle(doc, y, 'Session Notes');
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(...BRAND.textDark);
    const lines = doc.splitTextToSize(data.sessionNotes, doc.internal.pageSize.getWidth() - 32);
    doc.text(lines, 16, y);
    y += lines.length * 4 + 4;
  }

  const safeName = data.clientName.replace(/[^a-zA-Z0-9]/g, '-');
  finalizeAndDownload(doc, `SwanStudios-Workout-${safeName}-${data.date}.pdf`);
}


