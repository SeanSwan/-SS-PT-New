//  3. LONG-HORIZON PLAN PDF
// =====================================================================

export function exportLongHorizonPDF(data: PDFLongHorizonPlan, clientName?: string): void {
  const doc = createPDF();
  let y = addHeader(doc, `${data.horizonMonths}-Month Training Plan`, `${data.planName}${clientName ? ` · ${clientName}` : ''}`);

  // Plan overview
  y = addSectionTitle(doc, y, 'Plan Overview');
  y = addKeyValue(doc, y, 'Plan Name', data.planName);
  y = addKeyValue(doc, y, 'Duration', `${data.horizonMonths} months`);
  const totalWeeks = data.blocks.reduce((s, b) => s + b.durationWeeks, 0);
  y = addKeyValue(doc, y, 'Total Weeks', String(totalWeeks));
  y = addKeyValue(doc, y, 'Mesocycles', String(data.blocks.length));
  y += 2;

  if (data.summary) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(...BRAND.textDark);
    const lines = doc.splitTextToSize(data.summary, doc.internal.pageSize.getWidth() - 32);
    doc.text(lines, 16, y);
    y += lines.length * 4 + 4;
  }

  // Timeline visual
  y = addSectionTitle(doc, y, 'Periodization Timeline');
  const barWidth = doc.internal.pageSize.getWidth() - 32;
  const barH = 10;
  const phaseColors: [number, number, number][] = [
    BRAND.midnightSapphire, BRAND.wingPurple, BRAND.iceWing, BRAND.gildedFern,
    BRAND.successGreen, BRAND.warnRed,
  ];

  let barX = 16;
  data.blocks.forEach((block, i) => {
    const w = (block.durationWeeks / totalWeeks) * barWidth;
    doc.setFillColor(...phaseColors[i % phaseColors.length]);
    doc.rect(barX, y, w, barH, 'F');
    if (w > 15) {
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(6);
      doc.setTextColor(...BRAND.white);
      doc.text(`${block.durationWeeks}wk`, barX + w / 2, y + barH / 2 + 1, { align: 'center' });
    }
    barX += w;
  });
  y += barH + 2;

  // Legend
  data.blocks.forEach((block, i) => {
    doc.setFillColor(...phaseColors[i % phaseColors.length]);
    doc.rect(16 + i * 35, y, 4, 4, 'F');
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(6);
    doc.setTextColor(...BRAND.textDark);
    doc.text(block.phaseName.slice(0, 12), 22 + i * 35, y + 3);
  });
  y += 10;

  // Mesocycle detail table
  y = addSectionTitle(doc, y, 'Mesocycle Breakdown');
  addAutoTable(doc, {
    startY: y,
    head: [['#', 'Phase', 'Framework', 'Focus', 'Weeks', 'Sessions/Wk', 'Entry Criteria']],
    body: data.blocks.map(b => [
      b.sequence,
      b.phaseName,
      b.nasmFramework,
      b.focus || '-',
      b.durationWeeks,
      b.sessionsPerWeek || '-',
      b.entryCriteria || '-',
    ]),
    theme: 'grid',
    headStyles: { fillColor: BRAND.midnightSapphire, textColor: BRAND.white, fontSize: 7, fontStyle: 'bold' },
    bodyStyles: { fontSize: 7, textColor: BRAND.textDark },
    alternateRowStyles: { fillColor: BRAND.lightGray },
    styles: { cellPadding: 2.5, lineColor: BRAND.borderGray, lineWidth: 0.2 },
    margin: { left: 16, right: 16 },
    columnStyles: { 0: { cellWidth: 8, halign: 'center' }, 1: { fontStyle: 'bold' } },
  });
  y = getLastAutoTableY(doc, y) + 6;

  // Detailed phase cards
  data.blocks.forEach((block, i) => {
    y = checkPageBreak(doc, y, 35);
    y = addSectionTitle(doc, y, `Phase ${block.sequence}: ${block.phaseName}`);
    y = addKeyValue(doc, y, 'Framework', block.nasmFramework);
    if (block.focus) y = addKeyValue(doc, y, 'Focus', block.focus);
    y = addKeyValue(doc, y, 'Duration', `${block.durationWeeks} weeks · ${block.sessionsPerWeek || '?'} sessions/week`);
    if (block.entryCriteria) y = addKeyValue(doc, y, 'Entry Criteria', block.entryCriteria);
    if (block.exitCriteria) y = addKeyValue(doc, y, 'Exit Criteria', block.exitCriteria);
    if (block.notes) {
      doc.setFont('helvetica', 'italic');
      doc.setFontSize(7);
      doc.setTextColor(...BRAND.textMuted);
      const noteLines = doc.splitTextToSize(block.notes, doc.internal.pageSize.getWidth() - 36);
      doc.text(noteLines, 18, y);
      y += noteLines.length * 3.5 + 3;
    }
    if (block.rationale) {
      doc.setFont('helvetica', 'italic');
      doc.setFontSize(7);
      doc.setTextColor(...BRAND.wingPurple);
      const rLines = doc.splitTextToSize(`Rationale: ${block.rationale}`, doc.internal.pageSize.getWidth() - 36);
      doc.text(rLines, 18, y);
      y += rLines.length * 3.5 + 4;
    }
    y += 2;
  });

  const fname = clientName ? clientName.replace(/[^a-zA-Z0-9]/g, '-') : 'Plan';
  finalizeAndDownload(doc, `SwanStudios-${data.horizonMonths}mo-Plan-${fname}.pdf`);
}


// =====================================================================
//  4. POPULATED LONG-HORIZON PLAN PDF (L3, 2026-05-02)
// =====================================================================
//
// Renders the per-day exercise breakdown for a plan whose
// `weeks[].days[].exercises[]` are populated by the L1 backend
// (workoutBuilderService). Distinct from `exportLongHorizonPDF` above —
// that exporter renders mesocycle SUMMARY only; this one walks every
// session in the horizon. For a 24-week × 4×/wk plan that is ~96
// session sections and ~576 exercise rows.
//
// Co-branding: Move Fitness clients get a text-based MF mark in the
// header. The receipt §G8 listed an MF logo image asset as a non-
// engineering blocker (Sean to confirm MF's approval before bundling
// the image asset). When that lands, swap the text mark for an
// `addImage()` call alongside the Swan brand bar.
//
// Light palette: receipt §6 flagged a Crystalline Swan light variant as
// a Gemini consult prerequisite. The conservative print-friendly
// palette below uses the existing BRAND constants (white bg, midnight-
