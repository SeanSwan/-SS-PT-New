// ── Core PDF Builder ─────────────────────────────────────────────────

function createPDF(orientation: 'portrait' | 'landscape' = 'portrait'): jsPDF {
  return new jsPDF({ orientation, unit: 'mm', format: 'a4' });
}

function addHeader(doc: jsPDF, title: string, subtitle?: string) {
  const pageW = doc.internal.pageSize.getWidth();

  // Top accent bar
  doc.setFillColor(...BRAND.midnightSapphire);
  doc.rect(0, 0, pageW, 18, 'F');
  doc.setFillColor(...BRAND.wingPurple);
  doc.rect(0, 18, pageW, 1.5, 'F');

  // Brand name
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(...BRAND.white);
  doc.text('SwanStudios', 14, 12);

  // Title
  doc.setFontSize(9);
  doc.setTextColor(...BRAND.frostWhite);
  doc.text(title.toUpperCase(), pageW - 14, 9, { align: 'right' });

  // Subtitle / date
  if (subtitle) {
    doc.setFontSize(7);
    doc.text(subtitle, pageW - 14, 14, { align: 'right' });
  }

  return 24; // Y position after header
}

function addFooter(doc: jsPDF, pageNum: number, totalPages: number) {
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();

  doc.setFillColor(...BRAND.frostWhite);
  doc.rect(0, pageH - 12, pageW, 12, 'F');
  doc.setDrawColor(...BRAND.borderGray);
  doc.line(14, pageH - 12, pageW - 14, pageH - 12);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.setTextColor(...BRAND.textMuted);
  doc.text('Generated by SwanStudios · sswanstudios.com', 14, pageH - 5);
  doc.text(`Page ${pageNum} of ${totalPages}`, pageW - 14, pageH - 5, { align: 'right' });
  doc.text(format(new Date(), 'MMM d, yyyy h:mm a'), pageW / 2, pageH - 5, { align: 'center' });
}

function addSectionTitle(doc: jsPDF, y: number, title: string): number {
  doc.setFillColor(...BRAND.frostWhite);
  doc.rect(14, y - 1, doc.internal.pageSize.getWidth() - 28, 8, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(...BRAND.midnightSapphire);
  doc.text(title, 16, y + 4.5);
  return y + 11;
}

function addKeyValue(doc: jsPDF, y: number, label: string, value: string, x = 16): number {
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(...BRAND.textMuted);
  doc.text(label + ':', x, y);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...BRAND.textDark);
  doc.text(String(value), x + doc.getTextWidth(label + ':  '), y);
  return y + 5;
}

function checkPageBreak(doc: jsPDF, y: number, needed: number): number {
  const pageH = doc.internal.pageSize.getHeight();
  if (y + needed > pageH - 18) {
    doc.addPage();
    return 14;
  }
  return y;
}

function finalizeAndDownload(doc: jsPDF, filename: string) {
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    addFooter(doc, i, totalPages);
  }
  doc.save(filename);
}

