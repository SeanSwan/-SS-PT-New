export function exportBootcampPDF(data: PDFBootcampPlan): void {
  const doc = createPDF('landscape');
  let y = addHeader(doc, 'Boot Camp Class Plan', `${data.name} · ${data.dayType.replace('_', ' ').toUpperCase()}`);

  // Class overview
  y = addSectionTitle(doc, y, 'Class Overview');
  y = addKeyValue(doc, y, 'Format', data.classFormat.replace(/_/g, ' '));
  y = addKeyValue(doc, y, 'Day Type', data.dayType.replace(/_/g, ' '));
  y = addKeyValue(doc, y, 'Duration', `${data.totalClassMin} min total (${data.totalWorkoutMin} min workout)`);
  y = addKeyValue(doc, y, 'Stations', String(data.stationCount));
  y = addKeyValue(doc, y, 'Participants', String(data.expectedParticipants));
  y += 3;

  // Station layout
  if (data.stations.length > 0) {
    y = addSectionTitle(doc, y, 'Station Layout');
    addAutoTable(doc, {
      startY: y,
      head: [['#', 'Station Name', 'Equipment Needed']],
      body: data.stations.map(s => [s.stationNumber, s.stationName, s.equipmentNeeded || 'None']),
      theme: 'grid',
      headStyles: { fillColor: BRAND.midnightSapphire, textColor: BRAND.white, fontSize: 8, fontStyle: 'bold' },
      bodyStyles: { fontSize: 8, textColor: BRAND.textDark },
      alternateRowStyles: { fillColor: BRAND.lightGray },
      styles: { cellPadding: 2.5, lineColor: BRAND.borderGray, lineWidth: 0.2 },
      margin: { left: 16, right: 16 },
    });
    y = getLastAutoTableY(doc, y) + 6;
  }

  // Exercises by station
  const stationGroups = new Map<number, PDFBootcampExercise[]>();
  data.exercises.forEach(ex => {
    const si = ex.stationIndex ?? 0;
    if (!stationGroups.has(si)) stationGroups.set(si, []);
    stationGroups.get(si)!.push(ex);
  });

  stationGroups.forEach((exList, stationIdx) => {
    y = checkPageBreak(doc, y, 25);
    const stationName = data.stations.find(s => s.stationNumber === stationIdx + 1)?.stationName || `Station ${stationIdx + 1}`;
    y = addSectionTitle(doc, y, stationName);

    addAutoTable(doc, {
      startY: y,
      head: [['Exercise', 'Duration', 'Rest', 'Muscles', 'Equipment', 'Easy Var.', 'Hard Var.']],
      body: exList.map(ex => [
        ex.exerciseName,
        `${ex.durationSec}s`,
        `${ex.restSec}s`,
        ex.muscleTargets || '-',
        ex.equipmentRequired || 'BW',
        ex.easyVariation || '-',
        ex.hardVariation || '-',
      ]),
      theme: 'grid',
      headStyles: { fillColor: BRAND.wingPurple, textColor: BRAND.white, fontSize: 7, fontStyle: 'bold' },
      bodyStyles: { fontSize: 7, textColor: BRAND.textDark },
      alternateRowStyles: { fillColor: BRAND.lightGray },
      styles: { cellPadding: 2, lineColor: BRAND.borderGray, lineWidth: 0.2 },
      margin: { left: 16, right: 16 },
      columnStyles: { 0: { fontStyle: 'bold', cellWidth: 45 } },
    });
    y = getLastAutoTableY(doc, y) + 5;
  });

  // Cardio finishers
  const finishers = data.exercises.filter(ex => ex.isCardioFinisher);
  if (finishers.length > 0) {
    y = checkPageBreak(doc, y, 20);
    y = addSectionTitle(doc, y, 'Cardio Finishers');
    addAutoTable(doc, {
      startY: y,
      head: [['Exercise', 'Duration', 'Rest', 'Muscles']],
      body: finishers.map(ex => [ex.exerciseName, `${ex.durationSec}s`, `${ex.restSec}s`, ex.muscleTargets || '-']),
      theme: 'grid',
      headStyles: { fillColor: BRAND.successGreen, textColor: BRAND.white, fontSize: 8, fontStyle: 'bold' },
      bodyStyles: { fontSize: 8, textColor: BRAND.textDark },
      styles: { cellPadding: 2.5, lineColor: BRAND.borderGray, lineWidth: 0.2 },
      margin: { left: 16, right: 16 },
    });
    y = getLastAutoTableY(doc, y) + 5;
  }

  // Overflow plan
  if (data.overflowPlan) {
    y = checkPageBreak(doc, y, 25);
    y = addSectionTitle(doc, y, 'Overflow Plan');
    y = addKeyValue(doc, y, 'Triggers at', `${data.overflowPlan.triggerCount}+ participants`);
    y = addKeyValue(doc, y, 'Strategy', data.overflowPlan.strategy);
    y = addKeyValue(doc, y, 'Lap Duration', `${data.overflowPlan.lapDurationMin} min`);
    if (data.overflowPlan.lapExercises.length > 0) {
      y += 2;
      addAutoTable(doc, {
        startY: y,
        head: [['Lap Exercise', 'Duration (min)']],
        body: data.overflowPlan.lapExercises.map(le => [le.name, le.durationMin]),
        theme: 'grid',
        headStyles: { fillColor: BRAND.gildedFern, textColor: BRAND.white, fontSize: 8, fontStyle: 'bold' },
        bodyStyles: { fontSize: 8, textColor: BRAND.textDark },
        styles: { cellPadding: 2.5, lineColor: BRAND.borderGray, lineWidth: 0.2 },
        margin: { left: 16, right: 16 },
      });
    }
  }

  // Modification reference
  const moddedExercises = data.exercises.filter(ex => ex.kneeMod || ex.shoulderMod || ex.ankleMod || ex.wristMod || ex.backMod);
  if (moddedExercises.length > 0) {
    y = checkPageBreak(doc, y, 25);
    y = addSectionTitle(doc, y, 'Injury Modifications Reference');
    addAutoTable(doc, {
      startY: y,
      head: [['Exercise', 'Knee', 'Shoulder', 'Ankle', 'Wrist', 'Back']],
      body: moddedExercises.map(ex => [
        ex.exerciseName,
        ex.kneeMod || '-', ex.shoulderMod || '-', ex.ankleMod || '-', ex.wristMod || '-', ex.backMod || '-',
      ]),
      theme: 'grid',
      headStyles: { fillColor: BRAND.warnRed, textColor: BRAND.white, fontSize: 7, fontStyle: 'bold' },
      bodyStyles: { fontSize: 7, textColor: BRAND.textDark },
      styles: { cellPadding: 2, lineColor: BRAND.borderGray, lineWidth: 0.2 },
      margin: { left: 16, right: 16 },
    });
  }

  finalizeAndDownload(doc, `SwanStudios-Bootcamp-${data.name.replace(/[^a-zA-Z0-9]/g, '-')}.pdf`);
}


