// ─────────────────────────────────────────────────────────────
// SECTION: Main — self-executing seeder
// PURPOSE: findOrCreate by exercise_key for idempotent seeding
// ─────────────────────────────────────────────────────────────
async function main() {
  try {
    console.log('Seeding NASM advanced equipment exercises...');
    console.log('Total exercises to process: ' + ALL_EXERCISES.length);
    let created = 0, skipped = 0, failed = 0;
    for (const exercise of ALL_EXERCISES) {
      try {
        const [, wasCreated] = await Exercise.findOrCreate({
          where: { exercise_key: exercise.exercise_key },
          defaults: exercise,
        });
        if (wasCreated) created++; else skipped++;
      } catch (err) {
        console.warn('Failed: ' + exercise.name + ' — ' + err.message);
        failed++;
      }
    }
    console.log('Created: ' + created);
    console.log('Skipped (already existed): ' + skipped);
    console.log('Failed: ' + failed);
    console.log('Total attempted: ' + ALL_EXERCISES.length);
    console.log('Done:', { created, skipped, failed, total: ALL_EXERCISES.length });
  } catch (err) {
    console.error('Seeder failed:', err);
    process.exit(1);
  }
  process.exit(0);
}
main();
